create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text,
  email text,
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);

-- Add thread ownership fields without dropping existing messages.
alter table public.contact_messages
  add column if not exists sender_id uuid references auth.users(id) on delete cascade,
  add column if not exists sender_type text not null default 'visitor';

alter table public.contact_messages alter column name drop not null;
alter table public.contact_messages alter column email drop not null;
alter table public.contact_messages drop constraint if exists contact_messages_name_check;
alter table public.contact_messages drop constraint if exists contact_messages_email_check;
alter table public.contact_messages drop constraint if exists contact_messages_message_check;
alter table public.contact_messages drop constraint if exists contact_messages_sender_type_check;
alter table public.contact_messages add constraint contact_messages_name_check
  check (name is null or char_length(name) between 2 and 100);
alter table public.contact_messages add constraint contact_messages_email_check
  check (email is null or char_length(email) between 5 and 254);
alter table public.contact_messages add constraint contact_messages_message_check
  check (char_length(message) between 1 and 5000);
alter table public.contact_messages add constraint contact_messages_sender_type_check
  check (sender_type in ('visitor', 'admin'));

-- Basic per-visitor throttling: at most 5 visitor messages per 10 minutes
-- and 30 per 24 hours. CAPTCHA or server-side IP throttling is still needed
-- to defend against automated clients that create many anonymous accounts.
create index if not exists contact_messages_sender_created_idx
  on public.contact_messages (sender_id, created_at desc)
  where sender_type = 'visitor';

create or replace function public.enforce_contact_message_rate_limit()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  recent_count integer;
begin
  if new.sender_type <> 'visitor' then
    return new;
  end if;

  -- Serialize checks for one visitor so concurrent sends cannot skip the cap.
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(new.sender_id::text), 0);

  select count(*) into recent_count
  from public.contact_messages
  where sender_id = new.sender_id
    and sender_type = 'visitor'
    and created_at >= now() - interval '10 minutes';
  if recent_count >= 5 then
    raise exception 'Too many messages. Please wait before sending again.'
      using errcode = 'P0001';
  end if;

  select count(*) into recent_count
  from public.contact_messages
  where sender_id = new.sender_id
    and sender_type = 'visitor'
    and created_at >= now() - interval '24 hours';
  if recent_count >= 30 then
    raise exception 'Daily message limit reached. Please try again later.'
      using errcode = 'P0001';
  end if;

  return new;
end;
$$;

drop trigger if exists contact_messages_rate_limit on public.contact_messages;
create trigger contact_messages_rate_limit
before insert on public.contact_messages
for each row execute function public.enforce_contact_message_rate_limit();

alter table public.contact_messages enable row level security;

-- Supabase projects created with restricted Data API defaults need explicit
-- table grants in addition to RLS policies. Anonymous Auth users use the
-- authenticated database role; the unauthenticated anon role gets no access.
revoke all on table public.contact_messages from public, anon, authenticated;
grant select, insert, delete on table public.contact_messages to authenticated;

drop policy if exists "Anyone can submit contact messages" on public.contact_messages;
drop policy if exists "Authenticated admin can read messages" on public.contact_messages;
drop policy if exists "Authenticated admin can delete messages" on public.contact_messages;
drop policy if exists "Visitors can read their own thread" on public.contact_messages;
drop policy if exists "Admin can read all conversations" on public.contact_messages;
drop policy if exists "Visitors can send messages in their thread" on public.contact_messages;
drop policy if exists "Admin can reply to conversations" on public.contact_messages;
drop policy if exists "Admin can delete conversations" on public.contact_messages;

create policy "Visitors can read their own thread"
on public.contact_messages for select to authenticated
using (sender_id = auth.uid());

create policy "Admin can read all conversations"
on public.contact_messages for select to authenticated
using (lower(trim(auth.jwt() ->> 'email')) = lower(trim('sajidasim506@gmail.com')));

create policy "Visitors can send messages in their thread"
on public.contact_messages for insert to authenticated
with check (sender_id = auth.uid() and sender_type = 'visitor');

create policy "Admin can reply to conversations"
on public.contact_messages for insert to authenticated
with check (
  lower(trim(auth.jwt() ->> 'email')) = lower(trim('sajidasim506@gmail.com'))
  and sender_type = 'admin'
  and sender_id is not null
);

create policy "Admin can delete conversations"
on public.contact_messages for delete to authenticated
using (lower(trim(auth.jwt() ->> 'email')) = lower(trim('sajidasim506@gmail.com')));

